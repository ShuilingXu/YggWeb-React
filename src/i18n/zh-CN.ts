export function t(key: string, values: Record<string, string | number> = {}): string {
  const text = messages[key]
  if (!text && import.meta.env.DEV) throw new Error(`missing translation: ${key}`)
  return (text || messages['common.error'] || '').replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ''),
  )
}
